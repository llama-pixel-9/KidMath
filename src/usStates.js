const CODES = new Set(US_STATES.map((s) => s.code));

/** True for a code in the list above (exact, upper-case). */
export function isUsStateCode(code) {
  return typeof code === "string" && CODES.has(code);
}

/** The state's name for a code, or null. */
export function usStateName(code) {
  return US_STATES.find((s) => s.code === code)?.name ?? null;
}
